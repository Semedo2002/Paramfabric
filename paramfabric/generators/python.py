"""Python constant module generation"""

from __future__ import annotations

from paramfabric.core.graph import ParameterGraph
from paramfabric.generators.common import comment_text, rendered_value


def generate_python(graph: ParameterGraph) -> str:
    lines=['"""Generated by paramfabric; do not edit by hand."""', ""]
    for parameter in graph.fabric.parameters:
        name = parameter.name.upper()
        if parameter.description:
            lines.append(f"# {comment_text(parameter.description)}")
        lines.append(f"# Unit: {parameter.unit}")
        if parameter.type == "str":
            value = repr(parameter.value)
            annotation = "str"
        elif parameter.type == "bool":
            value = "True" if parameter.value else "False"
            annotation = "bool"
        elif parameter.type == "int":
            value = str(int(graph.value(parameter.name).magnitude))
            annotation = "int"
        else:
            value = rendered_value(graph, parameter.name)
            annotation = "float"
        lines.extend((f"{name}: {annotation} = {value}  # [{parameter.unit}]", ""))
    return "\n".join(lines)
