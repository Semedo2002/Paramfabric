"""Rust constant module generation"""

from __future__ import annotations

import json

from paramfabric.core.graph import ParameterGraph
from paramfabric.generators.common import comment_text, rendered_value


def generate_rust(graph: ParameterGraph) -> str:
    lines = ["// Generated by paramfabric; do not edit by hand.", ""]
    for parameter in graph.fabric.parameters:
        name = parameter.name.upper()
        if parameter.description:
            lines.append(f"/// {comment_text(parameter.description)}")
        lines.append(f"/// Unit: {parameter.unit}")
        if parameter.type == "str":
            value, rust_type = json.dumps(str(parameter.value)), "&str"
        elif parameter.type == "bool":
            value, rust_type = ("true" if parameter.value else "false"), "bool"
        elif parameter.type == "int":
            value, rust_type = str(int(graph.value(parameter.name).magnitude)), "i64"
        else:
            value, rust_type = rendered_value(graph, parameter.name), "f64"
        lines.extend((f"pub const {name}: {rust_type} = {value};", ""))
    return "\n".join(lines)
