def explain_failure(command: str, code: int, lines: list[str]) -> str:
    """A failed utility's output as what happened, what to do, and the lines that matter (no start-up banner)"""
    useful = [line for line in lines if line.strip() and not _FOAM_BANNER.search(line)]
    text = "\n".join(lines)
    summary = next(((what, fix) for pattern, what, fix in FAILURE_HINTS if re.search(pattern, text, re.I)), None)
    head = f"{summary[0]} {summary[1]}\n\n" if summary else ""
    return f"{head}{command} failed (exit {code}):\n" + "\n".join(useful[-15:])


def windows_to_wsl(path: Path) -> str:
    resolved = str(Path(path).resolve())
    match = re.match(r"^([A-Za-z]):[\\/](.*)$", resolved)
    if not match:
        return resolved.replace("\\", "/")
    return f"/mnt/{match.group(1).lower()}/{match.group(2).replace(chr(92), '/')}"


ALLRUN_ENTER = r'''# OpenFOAM refuses paths with spaces or quotes: work through a clean link when needed.
case "$PWD" in *[!A-Za-z0-9_./+-]*) link="${TMPDIR:-/tmp}/paramfabric-case-$$"; ln -sfn "$PWD" "$link" && cd "$link" || exit 1 ;; esac'''

_DETECTED: dict[str, FoamLauncher | None] = {}


def detect_launcher(refresh: bool = False) -> FoamLauncher | None:
    """Find OpenFOAM, honouring `PARAMFABRIC_OPENFOAM`.

    The variable may be `none` (disable), `docker` (use the
    `PARAMFABRIC_OPENFOAM_DOCKER_IMAGE` image), `wsl:<distro>:<bashrc>`, or a
    path to an OpenFOAM `etc/bashrc`. Without it: `simpleFoam` on PATH, then
    (on Windows) every WSL distribution with OpenFOAM installed.
    """
    override = os.getenv("PARAMFABRIC_OPENFOAM", "")
    if override in _DETECTED and not refresh:
        return _DETECTED[override]
    launcher: FoamLauncher | None = None
    if override.lower() in {"none", "off", "0"}:
        launcher = None
    elif override.startswith("wsl:"):
        distro, _, bashrc = override[4:].partition(":")
        launcher=FoamLauncher("wsl", f"WSL {distro}: {bashrc}", distro, bashrc)
    elif override == "docker":
        launcher = FoamLauncher("docker", f"Docker {DOCKER_IMAGE}")
    elif override:
        launcher = FoamLauncher("native", f"sourced {override}", bashrc=override)
    elif shutil.which("simpleFoam"):
        launcher = FoamLauncher("native", shutil.which("simpleFoam") or "")
    elif os.name == "nt" and shutil.which("wsl.exe"):
        launcher = _detect_wsl()
    _DETECTED[override] = launcher
    return launcher


def _detect_wsl() -> FoamLauncher | None:
    try:
        listing = subprocess.run([_wsl(), "-l", "-q"], capture_output=True, stdin=subprocess.DEVNULL, timeout=20)
    except (OSError, subprocess.TimeoutExpired):
        return None
    text = listing.stdout.decode("utf-16-le", errors="ignore") if b"\x00" in listing.stdout else listing.stdout.decode(errors="ignore")
    for distro in [line.strip() for line in text.splitlines() if line.strip()]:
        if distro.lower().startswith("docker-desktop"):
            continue
        probe = "for f in " + " ".join(WSL_BASHRC_GLOBS) + "; do [ -f \"$f\" ] && echo \"$f\"; done | sort -V | tail -1"
        try:
            found = subprocess.run([_wsl(), "-d", distro, "--exec", "bash", "-c", probe], capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=60)
        except (OSError, subprocess.TimeoutExpired):
            continue
        bashrc = found.stdout.strip()
        if bashrc and bashrc.endswith("/etc/bashrc"):
            return FoamLauncher("wsl", f"WSL {distro}: {bashrc.rsplit('/etc/', 1)[0]}", distro, bashrc)
    return None


# native polyMesh writer

def _foam_header(cls: str, obj: str, location: str = "", note: str = "") -> str:
    note_line = f'    note        "{note}";\n' if note else ""
    location_line = f'    location    "{location}";\n' if location else ""
    return (
        "FoamFile\n{\n    version     2.0;\n    format      ascii;\n    arch        \"LSB;label=32;scalar=64\";\n"
        f"    class       {cls};\n{location_line}{note_line}    object      {obj};\n}}\n\n"
    )


PATCH_TYPES = {"inlet": "patch", "outlet": "patch", "wall": "wall", "slip": "patch",
               "interface": "mappedWall", "heatflux": "wall", "adiabatic": "wall"}


def compact(mesh: Any) -> Any:
    """Drop nodes no cell references (mid-side nodes of a quadratic mesh)"""
    used = np.unique(np.concatenate([conn.ravel() for conn in mesh.cells.values()]))
    if len(used) == len(mesh.nodes):
        return mesh
    remap = np.full(len(mesh.nodes), -1, dtype=np.int64)
    remap[used] = np.arange(len(used))
    cells = {kind: remap[conn] for kind, conn in mesh.cells.items()}
    groups = [type(g)(g.name, g.kind, {k: remap[c] for k, c in g.elements.items()}, g.source_faces) for g in mesh.boundaries]
    return type(mesh)(mesh.nodes[used], cells, groups, mesh.order, dict(mesh.statistics))


@dataclass
class PolyMeshInfo:
    cells: int
    faces: int
    internal_faces: int
    points: int
    patches: list[dict[str, Any]] = field(default_factory=list)
    topology: Any = None


def write_polymesh(case_dir: Path, mesh: Any, region: str | None = None, patch_extras: dict[str, str] | None = None) -> PolyMeshInfo:
    """Write `constant/polyMesh` from a linear volume mesh (tet/prism/pyramid/hex).

    OpenFOAM ordering rules are enforced: internal faces have owner < neighbour
    and appear in upper-triangular order; boundary faces follow, grouped by
    patch; every face's point order gives a normal from owner to neighbour
    (outward on the boundary).

    `region` writes `constant/<region>/polyMesh` (multi-region cases);
    `patch_extras` adds dictionary entries to named patches (e.g. the
    `sampleRegion`/`samplePatch` of `mappedWall` interfaces).
    """
    from paramfabric.solvers.fvm.topology import build_topology

    linear = compact(mesh.linear())
    topology = build_topology(linear)
    owner, neighbour = topology.owner.copy(), topology.neighbour.copy()
    nodes=topology.face_nodes
    internal = topology.internal
    swap = owner[internal] > neighbour[internal]
    owner[internal[swap]], neighbour[internal[swap]] = neighbour[internal[swap]], owner[internal[swap]]
    centres = topology.cell_centres
    order_internal = internal[np.lexsort((neighbour[internal], owner[internal]))]
    blocks, patches, start = [order_internal], [], len(order_internal)
    for patch in topology.patches:
        faces = np.sort(patch.faces)
        blocks.append(faces)
        kind = patch.kind if patch.kind in PATCH_TYPES else "wall"
        patches.append({"name": patch.name.replace(" ", "_").replace(":", "_"), "kind": kind, "type": PATCH_TYPES[kind], "nFaces": int(len(faces)), "startFace": int(start)})
        start += len(faces)
    order = np.concatenate(blocks)
    lines = []
    face_centres=topology.face_centres
    for face in order:
        corners=[int(n) for n in nodes[face] if n >= 0]
        polygon=linear.nodes[corners]
        normal = np.zeros(3)
        for i in range(len(polygon)):  # Newell normal of the stored point order
            a, b = polygon[i], polygon[(i + 1) % len(polygon)]
            normal += np.array([(a[1] - b[1]) * (a[2] + b[2]), (a[2] - b[2]) * (a[0] + b[0]), (a[0] - b[0]) * (a[1] + b[1])])
        target = (centres[neighbour[face]] if neighbour[face] >= 0 else face_centres[face]) - centres[owner[face]]
        if np.dot(normal, target) < 0:
            corners.reverse()
        lines.append(f"{len(corners)}({' '.join(map(str, corners))})")
    location=f"constant/{region}/polyMesh" if region else "constant/polyMesh"
    directory = case_dir / location
    directory.mkdir(parents=True, exist_ok=True)
    n_internal = len(order_internal)
    note = f"nPoints:{len(linear.nodes)}  nCells:{topology.cells}  nFaces:{len(order)}  nInternalFaces:{n_internal}"
    point_lines = "\n".join(f"({x:.12g} {y:.12g} {z:.12g})" for x, y, z in linear.nodes)
    (directory / "points").write_text(_foam_header("vectorField", "points", location) + f"{len(linear.nodes)}\n(\n{point_lines}\n)\n", encoding="ascii", newline="\n")
    (directory / "faces").write_text(_foam_header("faceList", "faces", location) + f"{len(lines)}\n(\n" + "\n".join(lines) + "\n)\n", encoding="ascii", newline="\n")
    (directory / "owner").write_text(_foam_header("labelList", "owner", location, note) + f"{len(order)}\n(\n" + "\n".join(map(str, owner[order])) + "\n)\n", encoding="ascii", newline="\n")
    (directory / "neighbour").write_text(_foam_header("labelList", "neighbour", location, note) + f"{n_internal}\n(\n" + "\n".join(map(str, neighbour[order_internal])) + "\n)\n", encoding="ascii", newline="\n")
    boundary = [f"{len(patches)}\n("]
    for patch in patches:
        group = "        inGroups    1(wall);\n" if patch["type"] in {"wall", "mappedWall"} else ""
        entries = [entry.strip() for entry in (patch_extras or {}).get(patch["name"], "").split(";") if entry.strip()]
        extra = "".join(f"        {entry};\n" for entry in entries)
        boundary.append(
            f"    {patch['name']}\n    {{\n        type        {patch['type']};\n{group}{extra}"
            f"        nFaces      {patch['nFaces']};\n        startFace   {patch['startFace']};\n    }}"
        )
    boundary.append(")\n")
    (directory / "boundary").write_text(_foam_header("polyBoundaryMesh", "boundary", location) + "\n".join(boundary), encoding="ascii", newline="\n")
    return PolyMeshInfo(topology.cells, len(order), n_internal, len(linear.nodes), patches, topology)


