def archive_case(case_dir: Path, destination: Path) -> Path:
    import zipfile

    with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
        for path in sorted(case_dir.rglob("*")):
            relative = path.relative_to(case_dir)
            if path.is_file() and not relative.parts[0].startswith("processor"):
                archive.write(path, (Path(case_dir.name) / relative).as_posix())
    return destination


