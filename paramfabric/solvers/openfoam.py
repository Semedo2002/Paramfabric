def latest_time(case_dir: Path) -> Path | None:
    times = []
    for entry in case_dir.iterdir():
        try:
            value = float(entry.name)
        except ValueError:
            continue
        if entry.is_dir() and value > 0:
            times.append((value, entry))
    return max(times)[1] if times else None


def read_internal_field(path: Path) -> np.ndarray:
    """Parse an ASCII volScalarField/volVectorField internalField (uniform or nonuniform)"""
    text = path.read_text(encoding="utf-8", errors="replace")
    match = re.search(r"internalField\s+(uniform|nonuniform)\s+(.*?);\s*\n\s*boundaryField", text, re.DOTALL)
    if not match:
        raise ValueError(f"no internalField in {path}")
    kind, body = match.groups()
    vector = re.search(r"class\s+\w*VectorField", text) is not None
    if kind == "uniform":
        values=[float(v) for v in re.findall(r"[-+0-9.eE]+", body)]
        return np.array(values if vector else values[:1], float)
    list_match = re.search(r"List<(?:scalar|vector)>\s*(\d+)\s*\((.*)\)", body, re.DOTALL)
    if not list_match:
        raise ValueError(f"unsupported internalField layout in {path}")
    count = int(list_match.group(1))
    numbers = np.array(re.sub(r"[()]", " ", list_match.group(2)).split(), float)
    return numbers.reshape(count, 3) if vector else numbers[:count]


def read_force_coefficients(case_dir: Path) -> dict[str, list[float]]:
    """Columns of postProcessing/forceCoeffs/<time>/coefficient.dat keyed by header name"""
    files = sorted((case_dir / "postProcessing" / "forceCoeffs").glob("*/coefficient*.dat")) or sorted((case_dir / "postProcessing" / "forceCoeffs").glob("*/forceCoeffs*.dat"))
    if not files:
        return {}
    header: list[str] = []
    rows: list[list[float]] = []
    for line in files[-1].read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("#"):
            names = line.lstrip("#").split()
            if names and names[0] == "Time":
                header = names
            continue
        if line.strip():
            rows.append([float(value) for value in line.split()])
    if not header or not rows:
        return {}
    columns = list(zip(*rows))
    return {name: list(columns[index]) for index, name in enumerate(header) if index < len(columns)}


def read_legacy_vtk_polydata(path: Path) -> dict[str, Any]:
    """Read OpenFOAM's legacy ASCII VTK surface output (POLYDATA with POINT/CELL fields)"""
    tokens = path.read_text(encoding="ascii", errors="replace").split()
    index = tokens.index("POINTS")
    count = int(tokens[index + 1])
    points = np.array(tokens[index + 3 : index + 3 + 3 * count], float).reshape(-1, 3)
    index += 3 + 3 * count
    triangles: list[list[int]] = []
    while index < len(tokens) and tokens[index] not in {"POLYGONS", "POLYS"}:
        index += 1
    if index < len(tokens):
        n_polys, size = int(tokens[index + 1]), int(tokens[index + 2])
        index += 3
        if tokens[index] == "OFFSETS":
            raise ValueError("VTK 5.1 offset layout is not supported; request legacy output")
        end=index + size
        while index < end:
            n = int(tokens[index])
            polygon = [int(t) for t in tokens[index + 1 : index + 1 + n]]
            for k in range(1, n - 1):
                triangles.append([polygon[0], polygon[k], polygon[k + 1]])
            index += n + 1
    point_data: dict[str, np.ndarray] = {}
    cell_data: dict[str, np.ndarray] = {}
    section: dict[str, np.ndarray] | None = None
    section_count = 0
    while index < len(tokens):
        token = tokens[index]
        if token in {"POINT_DATA", "CELL_DATA"}:
            section = point_data if token == "POINT_DATA" else cell_data
            section_count = int(tokens[index + 1])
            index += 2
        elif token == "FIELD" and section is not None:
            arrays = int(tokens[index + 2])
            index += 3
            for _ in range(arrays):
                name, width, rows = tokens[index], int(tokens[index + 1]), int(tokens[index + 2])
                index += 4
                values = np.array(tokens[index : index + width * rows], float)
                section[name] = values.reshape(rows, width) if width > 1 else values
                index += width * rows
        elif token in {"SCALARS", "VECTORS"} and section is not None:
            name = tokens[index + 1]
            width = 3 if token == "VECTORS" else 1
            index += 3
            if token == "SCALARS" and tokens[index].isdigit():
                index += 1
            if tokens[index] == "LOOKUP_TABLE":
                index += 2
            values = np.array(tokens[index : index + width * section_count], float)
            section[name] = values.reshape(-1, 3) if width == 3 else values
            index += width * section_count
        else:
            index += 1
    return {"points": points, "triangles": np.array(triangles, int).reshape(-1, 3), "point_data": point_data, "cell_data": cell_data}


def find_surface(case_dir: Path, name: str) -> Path | None:
    files = sorted((case_dir / "postProcessing" / "surfaces").glob(f"*/{name}*.vtk"), key=lambda p: float(p.parent.name) if p.parent.name.replace(".", "", 1).isdigit() else 0)
    return files[-1] if files else None


def read_patch_field(path: Path, patch: str) -> np.ndarray:
    """Values of one patch in a field file's boundaryField (nonuniform or uniform)"""
    text = path.read_text(encoding="utf-8", errors="replace")
    boundary = text[text.index("boundaryField"):]
    match=re.search(rf"\b{re.escape(patch)}\s*\{{(.*?)\n\s*\}}", boundary, re.DOTALL)
    if not match:
        return np.zeros(0)
    body = match.group(1)
    listed=re.search(r"value\s+nonuniform\s+List<(?:scalar|vector)>\s*(\d+)\s*\((.*?)\)\s*;", body, re.DOTALL)
    if listed:
        numbers = np.array(re.sub(r"[()]", " ", listed.group(2)).split(), float)
        count = int(listed.group(1))
        return numbers.reshape(count, -1) if len(numbers) > count else numbers
    uniform = re.search(r"value\s+uniform\s+([-+0-9.eE]+)\s*;", body)
    return np.array([float(uniform.group(1))]) if uniform else np.zeros(0)


# Studio pipeline

class OpenFOAMError(RuntimeError):
    """OpenFOAM is missing, or a utility failed"""


def available() -> tuple[bool, str]:
    launcher = detect_launcher()
    if launcher is None:
        return False, "OpenFOAM not found (PATH, WSL distributions, or PARAMFABRIC_OPENFOAM)"
    return True, launcher.detail


def _turbulence(options: dict[str, Any], physics: dict[str, float], length: float, log: Any) -> str:
    choice = str(options.get("turbulence", "auto"))
    if choice == "laminar":
        return "laminar"
    if choice == "auto":
        reynolds = physics["inlet_velocity"] * length / physics["kinematic_viscosity"]
        model = "laminar" if reynolds < 2000 else "kOmegaSST"
        log(f"Reynolds number {reynolds:.3g} → {model}")
        return model
    if choice not in MODEL_ALIASES:
        raise OpenFOAMError(f"unknown turbulence model {choice!r}")
    return MODEL_ALIASES[choice]


def _stream(launcher: FoamLauncher, command: list[str], case_dir: Path, context: Any, parser: ResidualParser | None = None) -> str:
    """Run a utility, mirroring output to `log.<name>` and the task log.

    On cancellation the solver is asked to write its current state and stop
    (`stopAt writeNow`, read at the next iteration); it is terminated if it
    has not stopped within `STOP_GRACE` seconds.
    """
    from paramfabric.server.tasks import TaskCancelled

    context.log("$ " + " ".join(command))
    process = subprocess.Popen(
        launcher.argv(command, case_dir), cwd=case_dir, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT, text=True, bufsize=1, errors="replace",
    )
    assert process.stdout is not None
    tail: list[str] = []
    stop_requested: float | None = None

    def report(completed: tuple[int, dict[str, float]] | None) -> None:
        nonlocal stop_requested
        try:
            if completed:
                context.progress(*completed)
            if stop_requested is None and context.cancelled:
                raise TaskCancelled("solve cancelled")
        except TaskCancelled:
            if stop_requested is None:
                stop_requested = time.monotonic()
                context.log("Cancel requested: asking OpenFOAM to write and stop")
                control=case_dir / "system" / "controlDict"
                if control.is_file():
                    text = control.read_text(encoding="utf-8")
                    control.write_text(text.replace("stopAt          endTime;", "stopAt          writeNow;"), encoding="utf-8", newline="\n")

    with open(case_dir / f"log.{command[0]}", "w", encoding="utf-8") as log_file:
        for line in process.stdout:
            log_file.write(line)
            tail = (tail + [line.rstrip()])[-40:]
            if parser is None:
                context.log(line.rstrip())
                report(None)
            else:
                report(parser.feed(line))
            if stop_requested is not None and time.monotonic() - stop_requested > STOP_GRACE:
                process.terminate()
                break
    if parser is not None:
        report(parser.flush())
    code = process.wait()
    if stop_requested is not None:
        raise TaskCancelled("solve cancelled")
    if code != 0:
        raise OpenFOAMError(explain_failure(command[0], code, tail))
    return "\n".join(tail)


@dataclass
class PreparedCase:
    case_dir: Path
    mesh: Any
    physics: dict[str, float]
    mesh_summary: dict[str, Any]
    info: PolyMeshInfo
    setup: FoamSetup
    internal: bool


def prepare_case(state: dict[str, Any], options: dict[str, Any], case_dir: Path, context: Any) -> PreparedCase:
    """Mesh the regenerated B-Rep with gmsh and write a complete simpleFoam case"""
    from paramfabric.solvers import native3d

    mesh, physics, mesh_options = native3d._mesh(state, "cfd", context)
    mesh_summary = native3d._mesh_summary(mesh, "cfd", mesh_options)
    solver_options = {**state["settings"].get("solver_options", {}), **options}
    internal = solver_options.get("domain") == "internal"
    low, high = native3d._bounds(state)
    span = high - low
    length = float(np.max(span))
    turbulence = _turbulence(solver_options, physics, length, context.log)
    setup = FoamSetup(
        velocity=(physics["inlet_velocity"], 0.0, 0.0), kinematic_viscosity=physics["kinematic_viscosity"],
        density=physics["fluid_density"], turbulence=turbulence,
        intensity=float(solver_options.get("turbulence_intensity", 0.05)),
        length_scale=(0.07 if internal else 0.01) * (float(np.min(span)) if internal else length),
        end_time=int(solver_options.get("max_iterations", 500)), reference_length=length,
        reference_area=1.0 if internal else float(span[1] * span[2]),
        slice_point=tuple(float(v) for v in (low + high) / 2),
        processors=max(1, int(solver_options.get("processors", 1))),
        residual_target=float(solver_options.get("tolerance", 1e-5)), inlet_normal=internal,
    )
    # expert controls (relaxation factors and linear-solver tolerances)
    for option, attribute in (("relax_velocity", "relax_velocity"), ("relax_turbulence", "relax_turbulence"),
                              ("relax_pressure", "relax_pressure"), ("linear_tolerance_p", "tolerance_pressure"),
                              ("linear_tolerance_u", "tolerance_velocity")):
        if solver_options.get(option) not in (None, ""):
            setattr(setup, attribute, float(solver_options[option]))
    setup.write_interval = setup.end_time
    shutil.rmtree(case_dir, ignore_errors=True)
    case_dir.mkdir(parents=True)
    info = write_polymesh(case_dir, mesh)
    write_simple_case(case_dir, info, setup)
    run = ["#!/bin/sh", 'cd "${0%/*}" || exit 1', ALLRUN_ENTER, "checkMesh > log.checkMesh 2>&1 || exit 1"]
    if setup.processors > 1:
        run += ["decomposePar -force > log.decomposePar 2>&1", f"mpirun -np {setup.processors} simpleFoam -parallel > log.simpleFoam 2>&1",
                "reconstructPar -latestTime > log.reconstructPar 2>&1"]
    else:
        run.append("simpleFoam > log.simpleFoam 2>&1")
    (case_dir / "Allrun").write_text("\n".join(run) + "\n", encoding="utf-8", newline="\n")
    context.log(f"polyMesh: {info.cells:,} cells, {info.faces:,} faces, patches {', '.join(p['name'] for p in info.patches)}")
    return PreparedCase(case_dir, mesh, physics, mesh_summary, info, setup, internal)


def solve(state: dict[str, Any], analysis: str, options: dict[str, Any], context: Any) -> dict[str, Any]:
    """Exact B-Rep -> gmsh mesh (with prism layers) -> polyMesh -> simpleFoam -> viewport payload"""
    if analysis != "cfd":
        raise OpenFOAMError("OpenFOAM runs CFD; structural analysis uses the native FEA engine")
    if {**state["settings"].get("solver_options", {}), **options}.get("heat_transfer", {}).get("enabled"):
        return solve_cht(state, options, context)
    launcher = detect_launcher()
    if launcher is None:
        raise OpenFOAMError(available()[1])
    context.log(f"OpenFOAM: {launcher.detail}")
    case = prepare_case(state, options, context.artifact_dir / "openfoam", context)
    report = _stream(launcher, ["checkMesh"], case.case_dir, _Quiet(context))
    warnings = []
    failed = re.search(r"Failed (\d+) mesh checks", report)
    if failed:
        warnings.append(f"checkMesh: {failed.group(0)} (see log.checkMesh)")
    context.log("checkMesh: " + ("Mesh OK" if not failed else failed.group(0)))
    context.check()
    processors = case.setup.processors
    if processors > 1:
        _stream(launcher, ["decomposePar", "-force"], case.case_dir, _Quiet(context))
        _stream(launcher, ["mpirun", "-np", str(processors), "simpleFoam", "-parallel"], case.case_dir, context, ResidualParser())
        _stream(launcher, ["reconstructPar", "-latestTime"], case.case_dir, _Quiet(context))
    else:
        _stream(launcher, ["simpleFoam"], case.case_dir, context, ResidualParser())
    result = _collect(case, state, warnings, context)
    archive_case(case.case_dir, context.artifact(CASE_ARCHIVE))
    result["case_archive"] = CASE_ARCHIVE
    return result


