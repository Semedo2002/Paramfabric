def solve_cht(state: dict[str, Any], options: dict[str, Any], context: Any) -> dict[str, Any]:
    """Studio pipeline: bodies (solid) inside the flow volume (fluid) -> chtMultiRegionSimpleFoam"""
    from paramfabric.meshing.gmsh_mesher import mesh_cht
    from paramfabric.meshing.mesh import VolumeMesh, write_vtk_unstructured
    from paramfabric.solvers import native3d, post
    from paramfabric.solvers.fvm.topology import cell_to_node

    launcher = detect_launcher()
    if launcher is None:
        raise OpenFOAMError(available()[1])
    solver_options = {**state["settings"].get("solver_options", {}), **options}
    heat = solver_options.get("heat_transfer", {})
    domain = state["scene"].get("flow_domain")
    if not domain:
        raise OpenFOAMError("conjugate heat transfer needs a flow volume around the bodies (Flow Volume tool)")
    physics = native3d._physics(state, "cfd")
    low, high = native3d._bounds(state)
    heaters = [(bc["selectors"][0]["point"], bc["selectors"][0].get("normal"))
               for bc in state["settings"].get("boundary_conditions", []) if bc.get("type") == "heat" and bc.get("selectors")]
    if not heaters:  # default: the bodies' bottom face
        heaters = [([(low[0] + high[0]) / 2, (low[1] + high[1]) / 2, float(low[2])], [0.0, 0.0, -1.0])]
    size = native3d.mesh_options(state, "cfd", physics).size
    context.log(f"CHT mesh: conforming fluid/solid regions, target size {size:.4g} m")
    meshes = mesh_cht(native3d._cad_files(state), domain["bbox_min"], domain["bbox_max"],
                      native3d.MeshOptions(size=size, min_size=size / 10, curvature=12), heater=heaters)
    setup = ChtSetup(
        velocity=physics["inlet_velocity"], inlet_temperature=float(heat.get("inlet_temperature", 293.15)),
        heater_power=float(heat.get("heater_power", 50.0)), fluid=str(heat.get("fluid", "water")),
        solid=str(heat.get("solid", "aluminium")), end_time=int(solver_options.get("max_iterations", 1500)),
        residual_target=float(solver_options.get("tolerance", 1e-6)),
    )
    if setup.fluid not in FLUIDS or setup.solid not in SOLIDS:
        raise OpenFOAMError(f"unknown material: fluids {sorted(FLUIDS)}, solids {sorted(SOLIDS)}")
    case_dir = context.artifact_dir / "openfoam"
    shutil.rmtree(case_dir, ignore_errors=True)
    case_dir.mkdir(parents=True)
    infos = write_cht_case(case_dir, meshes, setup)
    context.log(f"Regions: fluid {infos['fluid'].cells:,} cells, solid {infos['solid'].cells:,} cells · "
                f"{setup.fluid} / {setup.solid} · heater {setup.heater_power:g} W "
                + (f"on {infos['fluid'].heater_area * 1e6:.0f} mm²" if infos["fluid"].heater_mode == "surface"  # type: ignore[attr-defined]
                   else "generated uniformly in the solid (the bodies are fully immersed: no unwetted face to heat)"))
    warnings = []
    if infos["fluid"].cells + infos["solid"].cells > CHT_SLOW_CELLS:
        context.log(f"This mesh is large for a coupled heat-transfer solve and may take a long time on one core. "
                    f"For a first look, lower mesh_fineness_ratio or reduce the iterations ({setup.end_time} now).")
    for region in ("fluid", "solid"):
        report = _stream(launcher, ["checkMesh", "-region", region], case_dir, _Quiet(context))
        if re.search(r"Failed (\d+) mesh checks", report):
            warnings.append(f"checkMesh -region {region} reported failed checks")
    _stream(launcher, ["chtMultiRegionSimpleFoam"], case_dir, context, ResidualParser())
    last = latest_time(case_dir)
    if last is None:
        raise OpenFOAMError("chtMultiRegionSimpleFoam wrote no results")
    summary = cht_summary(case_dir, setup)
    iterations = int(float(last.name))
    summary.update(converged=iterations < setup.end_time, iterations=iterations, fluid_cells=infos["fluid"].cells,
                   heater_mode=infos["fluid"].heater_mode,  # type: ignore[attr-defined]
                   solid_cells=infos["solid"].cells, fluid=setup.fluid, solid=setup.solid)
    if summary.get("energy_balance_error") is not None and abs(summary["energy_balance_error"]) > 0.02:
        warnings.append(f"energy balance off by {summary['energy_balance_error']:.1%}: run more iterations")
    elif not summary["converged"] and summary.get("energy_balance_error") is not None:
        summary["converged"] = True
        summary["convergence"] = f"energy balance closed to {abs(summary['energy_balance_error']):.2%}"
    regions = {}
    for region in ("fluid", "solid"):
        linear = compact(meshes[region].linear())
        temperature = read_internal_field(last / region / "T")
        regions[region] = (linear, infos[region].topology, cell_to_node(infos[region].topology, temperature))
    fluid_mesh, fluid_topology, fluid_t = regions["fluid"]
    velocity = read_internal_field(last / "fluid" / "U")
    node_u = cell_to_node(fluid_topology, velocity)
    solid_mesh, _, solid_t = regions["solid"]
    surface = post.exterior_surface(solid_mesh)
    surfaces = [{"name": "solid", "positions": surface["positions"], "indices": surface["indices"],
                 "values": {"temperature": solid_t[surface["nodes"]].tolist()}}]
    fluid_volume = post.volume_payload(fluid_mesh, {"temperature": fluid_t, "speed": np.linalg.norm(node_u, axis=1)}, {"U": node_u})
    solid_volume=post.volume_payload(solid_mesh, {"temperature": solid_t, "speed": np.zeros(len(solid_mesh.nodes))}, {"U": np.zeros((len(solid_mesh.nodes), 3))})
    volume = _merge_volumes(fluid_volume, solid_volume)
    offset = len(fluid_mesh.nodes)
    cells = {}
    for kind in {*fluid_mesh.cells, *solid_mesh.cells}:
        parts = [conn for conn in (fluid_mesh.cells.get(kind), None if kind not in solid_mesh.cells else solid_mesh.cells[kind] + offset) if conn is not None]
        cells[kind] = np.vstack(parts)
    combined = VolumeMesh(np.vstack([fluid_mesh.nodes, solid_mesh.nodes]), cells)
    write_vtk_unstructured(context.artifact("cht.vtk"), combined, point_data={"T": np.concatenate([fluid_t, solid_t])}, title="Paramfabric CHT result")
    summary["reliable"] = not warnings
    summary["warnings"] = warnings
    for warning in warnings:
        context.log(f"WARNING: {warning}")
    context.log(f"Heat to coolant {summary.get('heat_to_fluid', 0):.4g} W of {setup.heater_power:g} W · max solid T {summary.get('max_solid_temperature', 0):.2f} K")
    archive_case(case_dir, context.artifact(CASE_ARCHIVE))
    return {
        "analysis": "cfd", "engine": "openfoam", "physics": "cht",
        "method": f"OpenFOAM chtMultiRegionSimpleFoam · {setup.fluid}/{setup.solid} · {infos['fluid'].cells + infos['solid'].cells:,} cells",
        "converged": summary["converged"], "iterations": iterations,
        "surfaces": surfaces, "slice": {"positions": [], "indices": [], "values": {}}, "streamlines": [],
        "field_names": ["temperature", "speed"],
        "units": {"temperature": "K", "speed": "m/s"},
        "summary": summary, "volume": volume, "ports": post.port_glyphs(fluid_mesh, node_u),
        "vtk": "cht.vtk", "case_archive": CASE_ARCHIVE, "case_dir": str(case_dir),
    }


def _merge_volumes(first: dict[str, Any] | None, second: dict[str, Any] | None) -> dict[str, Any] | None:
    if not first or not second:
        return first or second
    offset=len(first["positions"]) // 3
    return {
        "positions": first["positions"] + second["positions"],
        "tets": first["tets"] + [index + offset for index in second["tets"]],
        "scalars": {name: first["scalars"][name] + second["scalars"].get(name, [0.0] * (len(second["positions"]) // 3)) for name in first["scalars"]},
        "vectors": {name: first["vectors"][name] + second["vectors"].get(name, [0.0] * len(second["positions"])) for name in first["vectors"]},
    }
