@dataclass
class FoamLauncher:
    """How OpenFOAM utilities are started: natively, inside WSL, or in Docker"""

    mode: str  # "native" | "wsl" | "docker"
    detail: str
    distro: str | None = None
    bashrc: str | None = None

    def argv(self, command: list[str], case_dir: Path) -> list[str]:
        if self.mode == "native":
            clean = foam_safe_path(str(Path(case_dir).resolve()))
            if not self.bashrc and clean:
                return command
            source = f"source {shlex.quote(self.bashrc)} >/dev/null 2>&1; " if self.bashrc else ""
            enter = "" if clean else f"{enter_case(str(Path(case_dir).resolve()))} && "
            return ["bash", "-c", f"{source}{enter}{shlex.join(command)}"]
        if self.mode == "wsl":
            inner = f"source {shlex.quote(self.bashrc or '')} >/dev/null 2>&1; {enter_case(windows_to_wsl(case_dir))} && {shlex.join(command)}"
            return [_wsl(), "-d", self.distro or "Ubuntu", "--exec", "bash", "-c", inner]
        mount = str(case_dir.resolve())
        return ["docker", "run", "--rm", "-v", f"{mount}:/case", "-w", "/case", DOCKER_IMAGE, "bash", "-lc", shlex.join(command)]

    def run(self, command: list[str], case_dir: Path, timeout: float | None = None) -> subprocess.CompletedProcess[str]:
        return subprocess.run(self.argv(command, case_dir), cwd=case_dir, capture_output=True, text=True, errors="replace", stdin=subprocess.DEVNULL, timeout=timeout)


def _wsl() -> str:
    return shutil.which("wsl.exe") or str(Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32" / "wsl.exe")


def foam_safe_path(path: str) -> bool:
    return re.fullmatch(r"[A-Za-z0-9_./+\-]+", path) is not None


def enter_case(path: str) -> str:
    """Shell that changes into a case. A folder such as `.../ai cfd/...` is entered through a clean link:
    OpenFOAM takes the case path from `$PWD`, so it never sees the original name."""
    if foam_safe_path(path):
        return f"cd {shlex.quote(path)}"
    link = 'L="${TMPDIR:-/tmp}/paramfabric-$(id -u)/' + hashlib.sha256(path.encode()).hexdigest()[:16] + '"'
    return f'{link}; mkdir -p "$(dirname "$L")" && ln -sfn {shlex.quote(path)} "$L" && cd "$L"'


