def _write(case_dir: Path, files: dict[str, str]) -> list[str]:
    for relative, content in files.items():
        destination = case_dir / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8", newline="\n")
    return sorted(files)


def _region_field(cls: str, name: str, region: str, dims: str, internal: str, patches: list[dict[str, Any]], entries: dict[str, str]) -> str:
    lines = [_foam_header(cls, name, f"0/{region}"), f"dimensions {dims};", f"internalField uniform {internal};", "boundaryField", "{"]
    for patch in patches:
        lines += [f"    {patch['name']}", "    {", "        " + entries[patch["kind"]], "    }"]
    lines.append("}")
    return "\n".join(lines) + "\n"


def write_cht_case(case_dir: Path, meshes: dict[str, Any], setup: ChtSetup) -> dict[str, PolyMeshInfo]:
    """Write a two-region (fluid, solid) chtMultiRegionSimpleFoam case"""
    fluid_props, solid_props = setup.fluid_data(), setup.solid_data()
    mapped = {
        "fluid": {"fluid_to_solid": "sampleMode nearestPatchFace; sampleRegion solid; samplePatch solid_to_fluid"},
        "solid": {"solid_to_fluid": "sampleMode nearestPatchFace; sampleRegion fluid; samplePatch fluid_to_solid"},
    }
    infos = {region: write_polymesh(case_dir, meshes[region], region=region, patch_extras=mapped[region]) for region in ("fluid", "solid")}
    fluid, solid = infos["fluid"].patches, infos["solid"].patches
    # A heater face must lie on the solid's outer boundary (not wetted by the coolant). Bodies that are
    # fully immersed have none: the power then goes in as uniform volumetric generation in the solid.
    volumetric = not any(p["kind"] == "heatflux" for p in solid)
    T0, p0, u = setup.inlet_temperature, setup.pressure, setup.velocity
    heater_area = 0.0
    solid_mesh=compact(meshes["solid"].linear())
    for group in solid_mesh.boundaries:
        if group.kind == "heatflux":
            for kind, conn in group.elements.items():
                corners = solid_mesh.nodes[conn[:, :3]]
                heater_area += 0.5 * float(np.linalg.norm(np.cross(corners[:, 1] - corners[:, 0], corners[:, 2] - corners[:, 0]), axis=1).sum())
    coupled = "type compressible::turbulentTemperatureCoupledBaffleMixed; Tnbr T; kappaMethod {method}; value uniform {T0:g};"
    files: dict[str, str] = {}
    files["constant/regionProperties"] = _foam_header("dictionary", "regionProperties", "constant") + "regions\n(\n    fluid (fluid)\n    solid (solid)\n);\n"
