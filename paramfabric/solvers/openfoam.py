"""OpenFOAM integration: the production CFD engine.

Two case builders live here:

* **Body-fitted (production).** The Studio meshes the exact B-Rep with gmsh
  (tetrahedra plus prism inflation layers), :func:`write_polymesh` converts that
  mesh into a native `constant/polyMesh` (upper-triangular face order, patches
  grouped, normals owner -> neighbour), :func:`write_simple_case` writes a
  steady `simpleFoam` case (laminar or k-ω SST with wall functions, force
  coefficients, y⁺, wall shear, VTK surface sampling), and :func:`solve` runs
  `checkMesh` and the solver through a :class:`FoamLauncher`: natively, inside
  a WSL distribution, or in Docker. Results are read back from the ASCII time
  directories and legacy-VTK surfaces into the viewport payload.
* **Cartesian / snappyHexMesh (legacy).** :func:`write_case` writes a laminar
  blockMesh + snappyHexMesh case around the morphed STL; it remains for the
  zero-dependency path.

Case files use both OpenFOAM.org (`physicalProperties`,
`momentumTransport`) and OpenFOAM.com (`transportProperties`,
`turbulenceProperties`) naming.
"""

