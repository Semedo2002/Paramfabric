@dataclass
class FoamSetup:
    velocity: tuple[float, float, float]
    kinematic_viscosity: float
    density: float = 1.0
    turbulence: str = "kOmegaSST"  # "laminar", "kOmegaSST", "kEpsilon", or "SpalartAllmaras"
    intensity: float = 0.05
    length_scale: float = 0.01
    end_time: int = 400
    write_interval: int = 400
    reference_area: float = 1.0
    reference_length: float = 1.0
    slice_point: tuple[float, float, float] = (0.0, 0.0, 0.0)
    processors: int = 1
    residual_target: float = 1e-5
    inlet_normal: bool = False  # internal flow: |velocity| enters normal to the inlet patch
    relax_velocity: float = 0.9  # SIMPLEC (consistent) defaults
    relax_turbulence: float = 0.7
    relax_pressure: float | None = None  # none: no explicit pressure relaxation (SIMPLEC)
    tolerance_pressure: float = 1e-7  # linear-solver absolute tolerances
    tolerance_velocity: float = 1e-8


# transported turbulence fields per model: (name, dimensions, inlet key, wall condition)
TURBULENCE_FIELDS: dict[str, list[tuple[str, str, str, str]]] = {
    "laminar": [],
    "kOmegaSST": [
        ("k", "[0 2 -2 0 0 0 0]", "k", "type kqRWallFunction; value $internalField;"),
        ("omega", "[0 0 -1 0 0 0 0]", "omega", "type omegaWallFunction; value $internalField;"),
    ],
    "kEpsilon": [
        ("k", "[0 2 -2 0 0 0 0]", "k", "type kqRWallFunction; value $internalField;"),
        ("epsilon", "[0 2 -3 0 0 0 0]", "epsilon", "type epsilonWallFunction; value $internalField;"),
    ],
    "SpalartAllmaras": [
        ("nuTilda", "[0 2 -1 0 0 0 0]", "nuTilda", "type fixedValue; value uniform 0;"),
    ],
}
NUT_WALL = {
    "kOmegaSST": "nutkWallFunction", "kEpsilon": "nutkWallFunction",
    # Spalding's law covers the viscous sublayer through the log layer
    "SpalartAllmaras": "nutUSpaldingWallFunction",
}
MODEL_ALIASES = {
    "laminar": "laminar", "k_omega_sst": "kOmegaSST", "kOmegaSST": "kOmegaSST", "k-omega-sst": "kOmegaSST",
    "k_epsilon": "kEpsilon", "k-epsilon": "kEpsilon", "kEpsilon": "kEpsilon",
    "spalart_allmaras": "SpalartAllmaras", "SpalartAllmaras": "SpalartAllmaras",
}


def turbulence_inlet(speed: float, intensity: float, length_scale: float, viscosity: float = 1.5e-5) -> dict[str, float]:
    k = 1.5 * (intensity * max(speed, 1e-12)) ** 2
    omega = math.sqrt(k) / (0.09 ** 0.25 * length_scale)
    return {"k": k, "omega": omega, "epsilon": 0.09 ** 0.75 * k ** 1.5 / length_scale, "nuTilda": 3.0 * viscosity}


def _boundary_field(patches: list[dict[str, Any]], entries: dict[str, str]) -> str:
    lines = ["boundaryField", "{"]
    for patch in patches:
        lines.append(f"    {patch['name']}")
        lines.append("    {")
        lines.append("        " + entries[patch["kind"]])
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def write_simple_case(case_dir: Path, info: PolyMeshInfo, setup: FoamSetup) -> list[str]:
    """Write 0/, constant/, system/ for simpleFoam on an existing polyMesh"""
    patches = info.patches
    walls = [p["name"] for p in patches if p["kind"] == "wall"]
    u = setup.velocity
    speed = math.sqrt(sum(c * c for c in u))
    inlet_turbulence = turbulence_inlet(speed, setup.intensity, setup.length_scale, setup.kinematic_viscosity)
    model_name = MODEL_ALIASES.get(setup.turbulence)
    if model_name is None:
        raise ValueError(f"unknown turbulence model {setup.turbulence!r}")
    turbulent = model_name != "laminar"
    transported = TURBULENCE_FIELDS[model_name]
    names=[name for name, *_ in transported]
    vector = f"({u[0]:.9g} {u[1]:.9g} {u[2]:.9g})"
    files: dict[str, str] = {}
    files["0/U"] = _foam_header("volVectorField", "U", "0") + f"dimensions [0 1 -1 0 0 0 0];\ninternalField uniform {vector};\n" + _boundary_field(patches, {
        "inlet": f"type surfaceNormalFixedValue; refValue uniform {-speed:.9g}; value uniform (0 0 0);"
        if setup.inlet_normal else f"type fixedValue; value uniform {vector};",
        "outlet": "type inletOutlet; inletValue uniform (0 0 0); value $internalField;",
        "wall": "type noSlip;",
        "slip": "type slip;",
    })
    files["0/p"] = _foam_header("volScalarField", "p", "0") + "dimensions [0 2 -2 0 0 0 0];\ninternalField uniform 0;\n" + _boundary_field(patches, {
        "inlet": "type zeroGradient;", "outlet": "type fixedValue; value uniform 0;", "wall": "type zeroGradient;", "slip": "type slip;",
    })
    if turbulent:
        for name, dims, key, wall in transported:
            value = inlet_turbulence[key]
            files[f"0/{name}"] = _foam_header("volScalarField", name, "0") + f"dimensions {dims};\ninternalField uniform {value:.9g};\n" + _boundary_field(patches, {
                "inlet": f"type fixedValue; value uniform {value:.9g};",
                "outlet": f"type inletOutlet; inletValue uniform {value:.9g}; value $internalField;",
                "wall": wall, "slip": "type slip;",
            })
        files["0/nut"] = _foam_header("volScalarField", "nut", "0") + "dimensions [0 2 -1 0 0 0 0];\ninternalField uniform 0;\n" + _boundary_field(patches, {
            "inlet": "type calculated; value uniform 0;", "outlet": "type calculated; value uniform 0;",
            "wall": f"type {NUT_WALL[model_name]}; value uniform 0;", "slip": "type slip;",
        })
    nu = f"nu [0 2 -1 0 0 0 0] {setup.kinematic_viscosity:.9g};\n"
    files["constant/transportProperties"] = _foam_header("dictionary", "transportProperties", "constant") + "transportModel Newtonian;\n" + nu
    files["constant/physicalProperties"] = _foam_header("dictionary", "physicalProperties", "constant") + "viscosityModel constant;\n" + nu
    model = f"simulationType RAS;\nRAS\n{{\n    model {model_name};\n    turbulence on;\n    printCoeffs off;\n}}\n" if turbulent else "simulationType laminar;\n"
    files["constant/turbulenceProperties"] = _foam_header("dictionary", "turbulenceProperties", "constant") + model
    files["constant/momentumTransport"] = _foam_header("dictionary", "momentumTransport", "constant") + model
    flow_dir = tuple(c / max(speed, 1e-12) for c in u)
    lift_dir = (0.0, 0.0, 1.0) if abs(flow_dir[2]) < 0.9 else (0.0, 1.0, 0.0)
    wall_list = " ".join(walls)
    sx, sy, sz = setup.slice_point
    functions = f"""functions
{{
    residuals {{ type solverInfo; libs (utilityFunctionObjects); fields (U p{''.join(' ' + n for n in names)}); }}
    wallShearStress {{ type wallShearStress; libs (fieldFunctionObjects); writeControl writeTime; patches ({wall_list}); }}
    {"yPlus { type yPlus; libs (fieldFunctionObjects); writeControl writeTime; }" if turbulent else ""}
    forceCoeffs
    {{
        type        forceCoeffs;
        libs        (forces);
        writeControl timeStep;
        writeInterval 1;
        patches     ({wall_list});
        rho         rhoInf;
        rhoInf      {setup.density:.9g};
        CofR        ({sx:.9g} {sy:.9g} {sz:.9g});
        liftDir     ({lift_dir[0]} {lift_dir[1]} {lift_dir[2]});
        dragDir     ({flow_dir[0]:.9g} {flow_dir[1]:.9g} {flow_dir[2]:.9g});
        pitchAxis   (0 1 0);
        magUInf     {speed:.9g};
        lRef        {setup.reference_length:.9g};
        Aref        {setup.reference_area:.9g};
    }}
    surfaces
    {{
        type            surfaces;
        libs            (sampling);
        writeControl    writeTime;
        surfaceFormat   vtk;
        formatOptions   {{ vtk {{ legacy true; format ascii; }} }};
        interpolate     true;
        fields          (p U wallShearStress);
        surfaces
        {{
            walls {{ type patch; patches ({wall_list}); interpolate true; }}
            slice {{ type cuttingPlane; point ({sx:.9g} {sy:.9g} {sz:.9g}); normal (0 0 1); interpolate true; }}
        }}
    }}
}}
"""
    files["system/controlDict"] = _foam_header("dictionary", "controlDict", "system") + f"""application     simpleFoam;
startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         {setup.end_time};
deltaT          1;
writeControl    timeStep;
writeInterval   {setup.write_interval};
purgeWrite      1;
writeFormat     ascii;
writePrecision  8;
runTimeModifiable true;
{functions}"""
    turbulent_div = "".join(f"\n    div(phi,{name}) bounded Gauss upwind;" for name in names)
    files["system/fvSchemes"] = _foam_header("dictionary", "fvSchemes", "system") + f"""ddtSchemes      {{ default steadyState; }}
gradSchemes     {{ default Gauss linear; grad(U) cellLimited Gauss linear 1; }}
divSchemes
{{
    default         none;
    div(phi,U)      bounded Gauss linearUpwind grad(U);{turbulent_div}
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}}
laplacianSchemes {{ default Gauss linear limited corrected 0.5; }}
interpolationSchemes {{ default linear; }}
snGradSchemes   {{ default limited corrected 0.5; }}
wallDist        {{ method meshWave; }}
"""
    turbulent_solvers = f'\n    "({"|".join(names)})" {{ solver smoothSolver; smoother symGaussSeidel; tolerance {setup.tolerance_velocity:g}; relTol 0.1; }}' if turbulent else ""
    turbulent_residual = "".join(f" {name} {setup.residual_target:g};" for name in names)
    pressure_relaxation = f"\n    fields {{ p {setup.relax_pressure:g}; }}" if setup.relax_pressure is not None else ""
    files["system/fvSolution"] = _foam_header("dictionary", "fvSolution", "system") + f"""solvers
{{
    p {{ solver GAMG; smoother GaussSeidel; tolerance {setup.tolerance_pressure:g}; relTol 0.05; }}
    U {{ solver smoothSolver; smoother symGaussSeidel; tolerance {setup.tolerance_velocity:g}; relTol 0.1; }}{turbulent_solvers}
}}

SIMPLE
{{
    nNonOrthogonalCorrectors 1;
    consistent      yes;
    residualControl {{ p {setup.residual_target:g}; U {setup.residual_target:g};{turbulent_residual} }}
}}

relaxationFactors
{{{pressure_relaxation}
    equations {{ U {setup.relax_velocity:g}; ".*" {setup.relax_turbulence:g}; }}
}}
"""
    if setup.processors > 1:
        files["system/decomposeParDict"] = _foam_header("dictionary", "decomposeParDict", "system") + f"numberOfSubdomains {setup.processors};\nmethod scotch;\n"
    for relative, content in files.items():
        destination = case_dir / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8", newline="\n")
    return sorted(files)


