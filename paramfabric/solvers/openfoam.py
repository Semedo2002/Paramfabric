def _collect(case: PreparedCase, state: dict[str, Any], warnings: list[str], context: Any) -> dict[str, Any]:
    from paramfabric.meshing.mesh import write_vtk_unstructured as write_vtk
    from paramfabric.solvers import post
    from paramfabric.solvers.fvm.topology import cell_to_node

    case_dir, mesh, info, setup, physics, internal = case.case_dir, case.mesh, case.info, case.setup, case.physics, case.internal
    rho=setup.density
    last = latest_time(case_dir)
    if last is None:
        raise OpenFOAMError("simpleFoam wrote no results")
    iterations = int(float(last.name))
    cell_u = read_internal_field(last / "U")
    cell_p = read_internal_field(last / "p") * rho
    if cell_u.ndim == 1:
        cell_u = np.tile(cell_u, (info.cells, 1))
    topology = info.topology
    linear = compact(mesh.linear())
    node_u = cell_to_node(topology, cell_u)
    node_p = cell_to_node(topology, cell_p)
    speed = np.linalg.norm(node_u, axis=1)
    point_data = {"U": node_u, "p": node_p, "speed": speed}
    if (last / "k").exists():
        point_data["k"] = cell_to_node(topology, read_internal_field(last / "k"))
        point_data["nut"] = cell_to_node(topology, read_internal_field(last / "nut"))
    write_vtk(context.artifact("flow.vtk"), linear, point_data=point_data, title="Paramfabric OpenFOAM result")

    surfaces = []
    wall_file = find_surface(case_dir, "walls")
    shear_max = 0.0
    if wall_file:
        walls = read_legacy_vtk_polydata(wall_file)
        shear = np.linalg.norm(walls["point_data"].get("wallShearStress", np.zeros((len(walls["points"]), 3))), axis=1) * rho
        shear_max=float(shear.max()) if len(shear) else 0.0
        surfaces.append({
            "name": "walls", "positions": np.round(walls["points"], 7).ravel().tolist(), "indices": walls["triangles"].ravel().tolist(),
            "values": {"pressure": (walls["point_data"]["p"] * rho).tolist(), "wall_shear": shear.tolist()},
        })
    section: dict[str, Any] = {"positions": [], "indices": [], "values": {}}
    slice_file = find_surface(case_dir, "slice")
    if slice_file:
        cut = read_legacy_vtk_polydata(slice_file)
        section = {
            "positions": np.round(cut["points"], 7).ravel().tolist(), "indices": cut["triangles"].ravel().tolist(),
            "values": {"pressure": (cut["point_data"]["p"] * rho).tolist(), "speed": np.linalg.norm(cut["point_data"]["U"], axis=1).tolist()},
        }

    low, high = linear.nodes.min(axis=0), linear.nodes.max(axis=0)
    span = high - low
    body_low, body_high = (np.array(state["scene"]["bodies"][0]["bbox_min"]), np.array(state["scene"]["bodies"][0]["bbox_max"])) if state["scene"]["bodies"] else (low, high)
    if internal:
        inlet = [g for g in mesh.boundaries if g.kind == "inlet"]
        seed_nodes=np.unique(np.concatenate([conn.ravel() for g in inlet for conn in g.elements.values()]))
        seeds = mesh.nodes[seed_nodes[:: max(1, len(seed_nodes) // 40)]]
        seeds = seeds + 0.25 * (seeds.mean(axis=0) - seeds)
    else:
        body_span = body_high - body_low
        ys = np.linspace(body_low[1] - 0.2 * body_span[1], body_high[1] + 0.2 * body_span[1], 8)
        zs = np.linspace(body_low[2] - 0.2 * body_span[2], body_high[2] + 0.2 * body_span[2], 5)
        seeds = np.array([[low[0] + 0.02 * span[0], y, z] for y in ys for z in zs])
    cell_size = float(np.cbrt(np.median(topology.volumes)))
    lines = post.streamlines(
        topology.cell_centres, cell_u, seeds, step=0.6 * cell_size,
        max_steps=int(4 * span.max() / (0.6 * cell_size)), max_gap=2.5 * cell_size,
    )

    coefficients = read_force_coefficients(case_dir)
    summary: dict[str, Any] = {
        "converged": iterations < setup.end_time, "iterations": iterations, "turbulence": setup.turbulence,
        "cells": info.cells, "max_wall_shear": shear_max, "solver": "OpenFOAM simpleFoam",
        "max_velocity": float(np.linalg.norm(cell_u, axis=1).max()),
        "pressure_range": [float(cell_p.min()), float(cell_p.max())],
    }
    if coefficients:
        final = {name: values[-1] for name, values in coefficients.items()}
        dynamic = 0.5 * rho * physics["inlet_velocity"] ** 2 * setup.reference_area
        summary.update(drag_coefficient=final.get("Cd", 0.0), lift_coefficient=final.get("Cl", 0.0), side_coefficient=final.get("Cs", 0.0))
        summary["drag"] = summary["drag_coefficient"] * dynamic
        if internal:
            summary.pop("drag_coefficient")
            summary.pop("lift_coefficient")
            summary.pop("side_coefficient")
    if (last / "yPlus").exists():
        values=np.concatenate([read_patch_field(last / "yPlus", p["name"]).ravel() for p in info.patches if p["kind"] == "wall"] or [np.zeros(0)])
        if len(values):
            summary["y_plus"] = {"min": float(values.min()), "mean": float(values.mean()), "max": float(values.max())}
            summary["mean_wall_y_plus"], summary["max_wall_y_plus"] = summary["y_plus"]["mean"], summary["y_plus"]["max"]
    if internal:
        inlet_cells = topology.owner[np.concatenate([p.faces for p in topology.patches if p.kind == "inlet"])]
        summary["pressure_drop"] = float(np.mean(cell_p[inlet_cells]))  # outlet is p = 0
    if not summary["converged"]:
        steady = _force_drift(coefficients)
        if steady is not None and steady < 0.005:
            summary["converged"] = True
            summary["convergence"] = f"force coefficients steady (±{steady:.2%} over the last 20% of iterations)"
            context.log(f"Residuals plateaued above {setup.residual_target:g}; {summary['convergence']}")
        else:
            warnings.append(f"residuals did not reach {setup.residual_target:g} in {setup.end_time} iterations")
    else:
        summary["convergence"] = f"residuals below {setup.residual_target:g}"
    summary["reliable"] = not warnings
    summary["warnings"] = warnings
    for warning in warnings:
        context.log(f"WARNING: {warning}")
    if "drag" in summary:
        context.log(f"Drag {summary['drag']:.4g} N" + (f", Cd {summary['drag_coefficient']:.4g}" if "drag_coefficient" in summary else ""))
    return {
        "analysis": "cfd", "engine": "openfoam",
        "method": f"OpenFOAM simpleFoam · {setup.turbulence} · {info.cells:,} cells",
        "converged": summary["converged"], "iterations": iterations,
        "surfaces": surfaces, "slice": section, "streamlines": lines,
        "units": {"pressure": "Pa", "speed": "m/s", "wall_shear": "Pa"},
        "summary": summary, "vtk": "flow.vtk", "case_dir": str(case_dir), "mesh": case.mesh_summary,
        "volume": post.volume_payload(linear, {"pressure": node_p, "speed": speed}, {"U": node_u}),
        "ports": post.port_glyphs(linear, node_u),
    }


def _force_drift(coefficients: dict[str, list[float]]) -> float | None:
    if not coefficients or len(coefficients.get("Time", [])) < 50:
        return None
    series = np.asarray(coefficients.get("Cd") or [], float)
    if not len(series):
        return None
    window = series[-max(10, len(series) // 5):]
    scale = max(abs(float(window.mean())), 1e-12)
    return float((window.max() - window.min()) / 2 / scale)


