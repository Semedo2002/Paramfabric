def read_function_object(case_dir: Path, region: str, name: str) -> dict[str, list[float]]:
    """Columns of `postProcessing/[<region>/]<name>/<time>/*.dat` keyed by header names"""
    roots = [case_dir / "postProcessing" / region / name, case_dir / "postProcessing" / name]
    files = [f for root in roots for f in sorted(root.glob("*/*.dat"))]
    if not files:
        return {}
    header, rows = [], []
    for line in files[-1].read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("#"):
            names = line.lstrip("#").split()
            if names and names[0] == "Time":
                header = names
        elif line.strip():
            rows.append([float(v) for v in line.split()])
    return {name: [row[i] for row in rows] for i, name in enumerate(header)} if header and rows else {}


def cht_summary(case_dir: Path, setup: ChtSetup) -> dict[str, Any]:
    """Energy balance and temperatures from a finished CHT run"""
    fluid = setup.fluid_data()
    outlet = read_function_object(case_dir, "fluid", "outletTemperature")
    flow = read_function_object(case_dir, "fluid", "outletMassFlow")
    solid = read_function_object(case_dir, "solid", "solidTemperature")
    t_out=next((v[-1] for k, v in outlet.items() if k.startswith("weightedAverage")), None)
    mass_flow = next((v[-1] for k, v in flow.items() if k.startswith("sum")), None)
    t_max = next((v[-1] for k, v in solid.items() if k.startswith("max")), None)
    summary: dict[str, Any] = {"inlet_temperature": setup.inlet_temperature, "outlet_temperature": t_out,
                               "mass_flow": mass_flow, "max_solid_temperature": t_max, "heater_power": setup.heater_power}
    if t_out is not None and mass_flow is not None:
        absorbed=abs(mass_flow) * fluid["Cp"] * (t_out - setup.inlet_temperature)
        summary["heat_to_fluid"] = absorbed
        summary["energy_balance_error"] = (absorbed - setup.heater_power) / setup.heater_power
    if t_max is not None and setup.heater_power:
        summary["thermal_resistance"] = (t_max - setup.inlet_temperature) / setup.heater_power  # K/W, inlet-referenced
    return summary


