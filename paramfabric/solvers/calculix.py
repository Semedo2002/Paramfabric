"""CalculiX (ccx) linear-static input writer and `.dat` displacement reader"""

from __future__ import annotations

import re
from pathlib import Path

from paramfabric.solvers.mesher import CartesianMesh

JOB_NAME = "paramfabric"


def write_input(case_dir: Path, mesh: CartesianMesh, *, young: float, poisson: float, load: float) -> list[str]:
    """Write C3D8 hex elements from solid voxels, clamp min-X, load max-X in −Z"""
    nx, ny, nz = mesh.shape
    cells=[
        (i, j, k) for k in range(nz) for j in range(ny) for i in range(nx) if mesh.solid[mesh.index(i, j, k)]
    ]
    if not cells:
        raise ValueError("there are no solid cells to analyse; refine the mesh")
    node_ids: dict[tuple[int, int, int], int] = {}
    elements = []
    for i, j, k in cells:
        corners=[
            (i, j, k), (i + 1, j, k), (i + 1, j + 1, k), (i, j + 1, k),
            (i, j, k + 1), (i + 1, j, k + 1), (i + 1, j + 1, k + 1), (i, j + 1, k + 1),
        ]
        elements.append([node_ids.setdefault(corner, len(node_ids) + 1) for corner in corners])
    min_i = min(key[0] for key in node_ids)
    max_i = max(key[0] for key in node_ids)
    fixed = [node for key, node in node_ids.items() if key[0] == min_i]
    loaded = [node for key, node in node_ids.items() if key[0] == max_i]
    lines = ["** Generated by Paramfabric Studio (SI units: m, N, Pa)", "*HEADING", "Paramfabric linear static", "*NODE"]
    for (i, j, k), node in sorted(node_ids.items(), key=lambda item: item[1]):
        x = mesh.origin[0] + i * mesh.spacing[0]
        y = mesh.origin[1] + j * mesh.spacing[1]
        z = mesh.origin[2] + k * mesh.spacing[2]
        lines.append(f"{node}, {x:.9g}, {y:.9g}, {z:.9g}")
    lines.append("*ELEMENT, TYPE=C3D8, ELSET=SOLID")
    lines.extend(f"{index}, " + ", ".join(map(str, nodes)) for index, nodes in enumerate(elements, start=1))

    def node_set(name: str, nodes: list[int]) -> None:
        lines.append(f"*NSET, NSET={name}")
        for start in range(0, len(nodes), 16):
            lines.append(", ".join(map(str, sorted(nodes)[start : start + 16])))

    node_set("FIXED", fixed)
    node_set("LOAD", loaded)
    lines += [
        "*MATERIAL, NAME=MAT", "*ELASTIC", f"{young:.9g}, {poisson:.9g}",
        "*SOLID SECTION, ELSET=SOLID, MATERIAL=MAT",
        "*BOUNDARY", "FIXED, 1, 3",
        "*STEP", "*STATIC", "*CLOAD",
    ]
    lines.extend(f"{node}, 3, {-load / len(loaded):.9g}" for node in sorted(loaded))
    lines += ["*NODE FILE", "U", "*EL FILE", "S", "*NODE PRINT, NSET=LOAD", "U", "*END STEP"]
    case_dir.mkdir(parents=True, exist_ok=True)
    (case_dir / f"{JOB_NAME}.inp").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return [f"{JOB_NAME}.inp"]


def read_load_displacements(dat_path: Path) -> list[tuple[int, float, float, float]]:
    """Parse `*NODE PRINT` displacements for the LOAD set from a `.dat` file"""
    if not dat_path.is_file():
        return []
    rows: list[tuple[int, float, float, float]] = []
    capture = False
    number = r"[+-]?\d*\.?\d+(?:[eE][+-]?\d+)?"
    for line in dat_path.read_text(encoding="utf-8", errors="replace").splitlines():
        if "displacements" in line.lower() and "load" in line.lower():
            capture = True
            continue
        if capture:
            match=re.match(rf"\s*(\d+)\s+({number})\s+({number})\s+({number})\s*$", line)
            if match:
                rows.append((int(match.group(1)), *(float(match.group(g)) for g in (2, 3, 4))))
            elif rows:
                capture = False
    return rows
