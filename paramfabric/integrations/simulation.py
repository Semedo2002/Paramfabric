"""ANSYS APDL, OpenFOAM dictionary, and COMSOL Java exporters"""

from __future__ import annotations

import json

from paramfabric.core.graph import ParameterGraph


def _numeric_parameters(graph: ParameterGraph) -> list[tuple[str, float, str]]:
    graph.evaluate()
    return [
        (parameter.name, float(graph.value(parameter.name).magnitude), parameter.unit)
        for parameter in graph.fabric.parameters
        if parameter.type not in {"str", "bool"}
    ]


def generate_ansys_apdl(graph: ParameterGraph) -> str:
    lines = ["! Generated by Paramfabric; values are expressed in each declared unit."]
    for name, value, unit in _numeric_parameters(graph):
        lines.extend((f"! {name} [{unit}]", f"{name.upper()} = {value:.15g}"))
    return "\n".join(lines) + "\n"


def generate_openfoam_dictionary(graph: ParameterGraph) -> str:
    """Generate a valid OpenFOAM dictionary of resolved scalar parameters"""
    lines = [
        "// Generated by Paramfabric; include this dictionary from case configuration.",
        "paramfabric",
        "{",
        "    version 2.0;",
        "    format ascii;",
        "    class dictionary;",
        '    object paramfabric;',
    ]
    for name, value, unit in _numeric_parameters(graph):
        lines.append(f"    {name} {value:.15g}; // [{unit}]")
    lines.extend(("}", ""))
    return "\n".join(lines)


def generate_comsol_java(graph: ParameterGraph, model_expression: str = "model") -> str:
    """Generate COMSOL Java API statements for model parameters"""
    if not model_expression.isidentifier():
        raise ValueError("model expression must be a Java identifier")
    lines = [
        "// Generated by Paramfabric; execute with a configured COMSOL Model object.",
        f"{model_expression}.param().label(\"Paramfabric parameters\");",
    ]
    for name, value, unit in _numeric_parameters(graph):
        comsol_value=f"{value:.15g}[{unit}]"
        lines.append(
            f"{model_expression}.param().set({json.dumps(name)}, {json.dumps(comsol_value)});"
        )
    return "\n".join(lines) + "\n"


def export_solver(graph: ParameterGraph, kind: str) -> str:
    exporters = {
        "ansys": generate_ansys_apdl,
        "openfoam": generate_openfoam_dictionary,
        "comsol": generate_comsol_java,
    }
    try:
        return exporters[kind](graph)
    except KeyError as exc:
        raise ValueError(f"unsupported simulation export format: {kind}") from exc
