"""OpenSCAD assignment exporter"""

from __future__ import annotations

from paramfabric.core.graph import ParameterGraph


def generate_openscad(graph: ParameterGraph) -> str:
    """Generate top-level OpenSCAD variables with unit and provenance comments"""
    graph.evaluate()
    lines = ["// Generated by Paramfabric. Values use each parameter's declared unit."]
    for parameter in graph.fabric.parameters:
        if parameter.type == "str":
            value = '"' + str(parameter.value).replace("\\", "\\\\").replace('"', '\\"') + '"'
        elif parameter.type == "bool":
            value = "true" if parameter.value else "false"
        else:
            value = f"{float(graph.value(parameter.name).magnitude):.15g}"
        lines.extend((f"// {parameter.description or parameter.name} [{parameter.unit}]", f"{parameter.name} = {value};"))
    return "\n".join(lines) + "\n"
